BEGIN;

CREATE TABLE IF NOT EXISTS quicknotes_users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS quicknotes_users_username_unique_idx
  ON quicknotes_users (LOWER(username));

ALTER TABLE notes
  ADD COLUMN IF NOT EXISTS user_id INTEGER
  REFERENCES quicknotes_users(id);

CREATE INDEX IF NOT EXISTS notes_user_id_idx
  ON notes (user_id);

COMMIT;
